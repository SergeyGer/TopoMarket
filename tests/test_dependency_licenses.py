"""Offline checks for the third-party dependency license audit (issue #10, EV01 context).

The audited registry is generated by ``scripts/refresh_dependency_licenses.py``
and verified offline here so a strong-copyleft dependency cannot silently enter
``pyproject.toml`` or ``requirements.lock``.
"""

from __future__ import annotations

import copy
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.audit_dependency_licenses import audit_registry  # noqa: E402
from scripts.refresh_dependency_licenses import classify, read_lock_pins  # noqa: E402

REGISTRY = ROOT / "docs" / "dependency_licenses.json"
REPORT = ROOT / "docs" / "DEPENDENCY_LICENSES.md"


def test_registry_exists_and_is_mit_compatible() -> None:
    registry = json.loads(REGISTRY.read_text(encoding="utf-8"))
    assert registry["schema_version"] == 1
    assert registry["policy"]["project_license"] == "MIT"
    assert registry["counts"]["fail"] == 0
    for name, entry in registry["packages"].items():
        assert entry["classification"] in {"permissive", "weak-copyleft"}, name
        if entry["classification"] == "permissive":
            assert entry["risk"] == "PASS", name
        else:
            assert entry["risk"] == "REVIEW", name


def test_offline_audit_passes_without_network() -> None:
    report = audit_registry(ROOT)
    assert report["passed"] is True, report["failures"]
    assert report["counts"]["total"] >= 50
    assert not [failure for failure in report["failures"] if "strong copyleft" in failure]


def test_every_lock_package_is_audited_with_the_same_version() -> None:
    registry = json.loads(REGISTRY.read_text(encoding="utf-8"))
    packages = registry["packages"]
    for name, version in read_lock_pins().items():
        assert name in packages, f"un-audited locked dependency: {name}"
        assert str(packages[name]["version"]) == version


def test_pyproject_declared_dependencies_are_audited() -> None:
    from scripts.audit_dependency_licenses import read_pyproject_names

    registry = json.loads(REGISTRY.read_text(encoding="utf-8"))
    missing = sorted(read_pyproject_names() - set(registry["packages"]))
    assert missing == [], missing


def test_docs_report_matches_registry() -> None:
    text = REPORT.read_text(encoding="utf-8")
    assert "no strong copyleft dependency found" in text.lower()
    assert "MIT" in text


def test_gpl_classification_is_detected() -> None:
    assert classify({"license_expression": "GPL-3.0-only"})["risk"] == "FAIL"
    assert classify({"license_expression": "AGPL-3.0-or-later"})["risk"] == "FAIL"
    assert (
        classify({"license_expression": "Apache-2.0 OR BSD-3-Clause"})["classification"]
        == "permissive"
    )
    assert classify({"license_expression": "MPL-2.0"})["classification"] == "weak-copyleft"
    assert classify({"license_expression": "MIT"})["classification"] == "permissive"
    assert (
        classify({"classifiers": ["License :: OSI Approved :: BSD License"]})["classification"]
        == "permissive"
    )
    # Dual-licensed BSD/GPL/public-domain packages are distributed under BSD terms.
    assert (
        classify(
            {
                "classifiers": [
                    "License :: OSI Approved :: BSD License",
                    "License :: OSI Approved :: GNU General Public License (GPL)",
                    "License :: Public Domain",
                ]
            }
        )["classification"]
        == "permissive"
    )


def test_audit_detects_a_strong_copyleft_addition(tmp_path: Path) -> None:
    """A hypothetical GPL dependency must fail the offline audit."""

    registry = json.loads(REGISTRY.read_text(encoding="utf-8"))
    poisoned = copy.deepcopy(registry)
    poisoned["packages"]["gpl-example"] = {
        "name": "gpl-example",
        "version": "1.0.0",
        "declared": "lock",
        "locked": True,
        "license": "GPL-3.0-only",
        "license_classifiers": [],
        "classification": "strong-copyleft",
        "evidence": ["GPL-3.0"],
        "risk": "FAIL",
        "metadata_source": "test",
    }
    (tmp_path / "docs").mkdir()
    (tmp_path / "docs" / "dependency_licenses.json").write_text(
        json.dumps(poisoned), encoding="utf-8"
    )
    (tmp_path / "requirements.lock").write_text("gpl-example==1.0.0\n", encoding="utf-8")
    (tmp_path / "pyproject.toml").write_text(
        '[project]\nname = "topomarket"\nversion = "0.0.0"\ndependencies = []\n',
        encoding="utf-8",
    )
    report = audit_registry(tmp_path)
    assert report["passed"] is False
    assert any("not allowed" in failure for failure in report["failures"])
