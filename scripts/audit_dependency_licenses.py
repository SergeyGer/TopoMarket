#!/usr/bin/env python3
"""Offline verification of the audited third-party license registry.

The registry ``docs/dependency_licenses.json`` is generated by
``scripts/refresh_dependency_licenses.py`` and committed so CI can verify the
dependency licenses without network access.  This script checks that:

* the registry covers every distribution pinned in ``requirements.lock`` (and in
  the Cloud ``requirements.txt`` when present) with the same version;
* every direct dependency declared in ``pyproject.toml`` is audited;
* no audited dependency is classified as strong copyleft (GPL/AGPL);
* no dependency is left unclassified.

Exit code 0 means the license posture is acceptable for the MIT distribution.

Usage::

    python scripts/audit_dependency_licenses.py
    python scripts/audit_dependency_licenses.py --json
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import tomllib

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "docs" / "dependency_licenses.json"
LOCKFILE = ROOT / "requirements.lock"
CLOUD_REQUIREMENTS = ROOT / "requirements.txt"
PYPROJECT = ROOT / "pyproject.toml"

ALLOWED_CLASSES = {"permissive", "weak-copyleft"}


def _requirement_name(requirement: str) -> str:
    import re

    return re.split(r"[<>=!~;\[ ]", requirement.strip())[0].lower().replace("_", "-")


def read_pyproject_names(path: Path = PYPROJECT) -> set[str]:
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    project = data["project"]
    names = {_requirement_name(requirement) for requirement in project.get("dependencies") or []}
    for values in (project.get("optional-dependencies") or {}).values():
        names.update(_requirement_name(requirement) for requirement in values)
    return names


def read_pins(path: Path) -> dict[str, str]:
    pins: dict[str, str] = {}
    if not path.is_file():
        return pins
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "==" not in line:
            continue
        name, version = line.split("==", 1)
        pins[_requirement_name(name)] = version.strip()
    return pins


def audit_registry(root: Path = ROOT) -> dict[str, Any]:
    registry_path = root / "docs" / "dependency_licenses.json"
    failures: list[str] = []
    warnings: list[str] = []
    if not registry_path.is_file():
        return {
            "passed": False,
            "failures": [f"registry missing: {registry_path}"],
            "warnings": [],
            "counts": {"total": 0, "pass": 0, "review": 0, "fail": 1},
        }
    registry = json.loads(registry_path.read_text(encoding="utf-8"))
    packages: dict[str, dict[str, Any]] = registry.get("packages") or {}
    lock_pins = read_pins(root / "requirements.lock")
    cloud_pins = read_pins(root / "requirements.txt")
    declared = read_pyproject_names(root / "pyproject.toml")

    for name, version in sorted(lock_pins.items()):
        entry = packages.get(name)
        if entry is None:
            failures.append(f"requirements.lock: {name} is not audited in the license registry")
            continue
        if str(entry.get("version")) != version:
            failures.append(
                f"requirements.lock: {name}=={version} does not match the audited "
                f"version {entry.get('version')}; refresh the registry"
            )
    for name, version in sorted(cloud_pins.items()):
        entry = packages.get(name)
        if entry is None:
            failures.append(f"requirements.txt: {name} is not audited in the license registry")
            continue
        if str(entry.get("version")) != version:
            failures.append(
                f"requirements.txt: {name}=={version} does not match the audited "
                f"version {entry.get('version')}; refresh the registry"
            )
    for name in sorted(declared):
        entry = packages.get(name)
        if entry is None:
            failures.append(f"pyproject.toml: {name} is not audited in the license registry")
            continue
        if not entry.get("locked") and name not in cloud_pins:
            warnings.append(
                f"pyproject.toml: {name} is declared but not pinned; pin it for release"
            )

    for name, entry in sorted(packages.items()):
        classification = entry.get("classification")
        if classification not in ALLOWED_CLASSES:
            failures.append(
                f"{name}: license class {classification!r} is not allowed for the MIT distribution "
                f"({entry.get('license')!r})"
            )
        elif classification == "weak-copyleft":
            warnings.append(
                f"{name}: weak copyleft ({entry.get('license')!r}) - used unmodified, reviewed"
            )

    counts = {
        "total": len(packages),
        "pass": sum(1 for entry in packages.values() if entry.get("risk") == "PASS"),
        "review": sum(1 for entry in packages.values() if entry.get("risk") == "REVIEW"),
        "fail": sum(1 for entry in packages.values() if entry.get("risk") == "FAIL"),
    }
    return {
        "passed": not failures,
        "project_license": "MIT",
        "counts": counts,
        "failures": failures,
        "warnings": warnings,
        "registry": str(
            registry_path.relative_to(root) if registry_path.is_relative_to(root) else registry_path
        ),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Audit third-party dependency licenses offline.")
    parser.add_argument("--json", action="store_true", help="Emit the JSON report.")
    args = parser.parse_args(argv)
    report = audit_registry(ROOT)
    if args.json:
        print(json.dumps(report, indent=2, sort_keys=True))
    else:
        counts = report["counts"]
        print(
            f"license audit: {counts['pass']} pass / {counts['review']} review / "
            f"{counts['fail']} fail of {counts['total']} audited packages"
        )
        for warning in report["warnings"]:
            print(f"note: {warning}")
        for failure in report["failures"]:
            print(f"FAIL: {failure}", file=sys.stderr)
        print("verdict:", "PASS - no strong copyleft dependencies" if report["passed"] else "FAIL")
    return 0 if report["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
