"""Deterministic synthetic data generation for TopoMarket.

The generator writes a small, self-contained market dataset made of CSV files
plus a ``manifest.json`` that records the generator name/version, the seed used,
the row counts, and a SHA-256 digest for every generated file.

Two runs with the same seed produce byte-identical CSV files and identical file
digests. The only value that intentionally changes between runs is the
manifest's ``created_at`` timestamp; the manifest's content-addressed
``snapshot_id`` ignores it, so it remains stable as well.
"""

from __future__ import annotations

import csv
import hashlib
import io
import math
import random
from collections.abc import Mapping, Sequence
from datetime import date, datetime, timedelta
from pathlib import Path
from typing import Any

from topomarket import __version__

from .manifest import (
    MANIFEST_GENERATOR,
    MANIFEST_SCHEMA_VERSION,
    _atomic_write_text,
    write_manifest,
)
from .normalized import build_demo_normalized_tables
from .schemas import NORMALIZED_FILE_NAMES, NORMALIZED_TABLE_NAMES, SCHEMA_CONTRACTS

#: Friendly alias used by the demo package and by schema-alignment callers.
DEMO_FILE_NAMES = NORMALIZED_FILE_NAMES

#: Human-readable generator name recorded in the manifest.
GENERATOR_NAME = "topomarket.synthetic"

#: The seed used when callers do not supply one.
DEFAULT_SEED = 42

#: Number of markets and daily price rows generated by default.
DEFAULT_MARKET_COUNT = 6
DEFAULT_PRICE_DAYS = 30

#: Fixed start date so price rows are stable across runs.
PRICE_START_DATE = date(2024, 1, 1)

#: Generated CSV files in their deterministic write order.  The first four are
#: the original scaffold fixtures; the final three are the normalised analysis
#: tables shared with the private import pipeline.
SYNTHETIC_FILE_NAMES: tuple[str, ...] = (
    "markets.csv",
    "participants.csv",
    "edges.csv",
    "prices.csv",
    *NORMALIZED_FILE_NAMES,
)

MARKET_COLUMNS: tuple[str, ...] = (
    "market_id",
    "name",
    "topology",
    "participants",
)
PARTICIPANT_COLUMNS: tuple[str, ...] = (
    "participant_id",
    "market_id",
    "role",
    "weight",
)
EDGE_COLUMNS: tuple[str, ...] = (
    "edge_id",
    "market_id",
    "source",
    "target",
    "weight",
)
PRICE_COLUMNS: tuple[str, ...] = (
    "date",
    "market_id",
    "price",
    "volume",
)

_TOPOLOGIES = ("ring", "star", "mesh", "tree", "grid", "complete")
_ROLES = ("maker", "taker", "router", "observer")


def normalise_seed(seed: Any) -> int:
    """Return ``seed`` as an integer, rejecting booleans and bad values."""

    if isinstance(seed, bool):
        raise ValueError("seed must be an integer")
    try:
        return int(seed)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"seed must be an integer, got {seed!r}") from exc


def _rng(seed: int, section: str) -> random.Random:
    """Return a section-specific RNG derived deterministically from ``seed``."""

    return random.Random(  # nosec B311 - deterministic fixtures, not cryptography
        f"topomarket-synthetic:{seed}:{section}"
    )


def _csv_text(header: Sequence[str], rows: Sequence[Sequence[Any]]) -> str:
    """Serialise rows as CSV with stable formatting and Unix line endings."""

    buffer = io.StringIO(newline="")
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(header)
    writer.writerows(rows)
    return buffer.getvalue()


def _market_rows(seed: int) -> tuple[list[tuple[Any, ...]], list[tuple[Any, ...]]]:
    """Build the markets and participants rows for ``seed``."""

    rng = _rng(seed, "markets")
    market_rows: list[tuple[Any, ...]] = []
    participant_rows: list[tuple[Any, ...]] = []

    for index in range(1, DEFAULT_MARKET_COUNT + 1):
        market_id = f"market-{index:03d}"
        topology = rng.choice(_TOPOLOGIES)
        number_of_participants = rng.randint(5, 12)
        market_rows.append(
            (
                market_id,
                f"Synthetic Market {index:02d}",
                topology,
                number_of_participants,
            )
        )
        for participant_index in range(1, number_of_participants + 1):
            participant_rows.append(
                (
                    f"{market_id}-p{participant_index:02d}",
                    market_id,
                    rng.choice(_ROLES),
                    f"{rng.uniform(0.1, 1.0):.4f}",
                )
            )

    return market_rows, participant_rows


def _participants_by_market(
    market_rows: Sequence[Sequence[Any]],
) -> dict[str, list[str]]:
    """Return participant identifiers grouped by market id."""

    grouped: dict[str, list[str]] = {}
    for market in market_rows:
        market_id = str(market[0])
        count = int(market[3])
        grouped[market_id] = [f"{market_id}-p{position:02d}" for position in range(1, count + 1)]
    return grouped


def _topology_edges(topology: str, participants: Sequence[str]) -> list[tuple[str, str]]:
    """Return deterministic source/target pairs for a topology."""

    nodes = list(participants)
    count = len(nodes)
    edges: list[tuple[str, str]] = []

    if topology == "ring":
        for index, source in enumerate(nodes):
            edges.append((source, nodes[(index + 1) % count]))
    elif topology == "star":
        centre = nodes[0]
        for target in nodes[1:]:
            edges.append((centre, target))
    elif topology in {"mesh", "complete"}:
        for left in range(count):
            for right in range(left + 1, count):
                edges.append((nodes[left], nodes[right]))
    elif topology == "tree":
        for index in range(1, count):
            edges.append((nodes[(index - 1) // 2], nodes[index]))
    elif topology == "grid":
        width = max(1, math.ceil(math.sqrt(count)))
        for index, source in enumerate(nodes):
            row, column = divmod(index, width)
            if column + 1 < width and index + 1 < count:
                edges.append((source, nodes[index + 1]))
            below = (row + 1) * width + column
            if below < count:
                edges.append((source, nodes[below]))
    else:  # pragma: no cover - defensive fallback for future topologies
        for left in range(count):
            for right in range(left + 1, count):
                edges.append((nodes[left], nodes[right]))

    return edges


def _edge_rows(seed: int, market_rows: Sequence[Sequence[Any]]) -> list[tuple[Any, ...]]:
    """Build the edges rows for ``seed``."""

    rng = _rng(seed, "edges")
    grouped = _participants_by_market(market_rows)
    rows: list[tuple[Any, ...]] = []
    edge_number = 1
    for market in market_rows:
        market_id = str(market[0])
        topology = str(market[2])
        for source, target in _topology_edges(topology, grouped[market_id]):
            rows.append(
                (
                    f"edge-{edge_number:05d}",
                    market_id,
                    source,
                    target,
                    f"{rng.uniform(0.1, 5.0):.4f}",
                )
            )
            edge_number += 1
    return rows


def _price_rows(seed: int, market_rows: Sequence[Sequence[Any]]) -> list[tuple[Any, ...]]:
    """Build the daily price rows for ``seed``."""

    rng = _rng(seed, "prices")
    rows: list[tuple[Any, ...]] = []
    for market_index, market in enumerate(market_rows):
        market_id = str(market[0])
        price = 100.0 + market_index * 10.0
        for day in range(DEFAULT_PRICE_DAYS):
            price = max(1.0, price + rng.uniform(-2.0, 2.0))
            rows.append(
                (
                    (PRICE_START_DATE + timedelta(days=day)).isoformat(),
                    market_id,
                    f"{price:.4f}",
                    rng.randint(100, 10_000),
                )
            )
    return rows


def build_dataset(
    seed: Any = DEFAULT_SEED,
) -> dict[str, tuple[tuple[str, ...], list[tuple[Any, ...]]]]:
    """Return the generated CSV contents keyed by file name.

    The result maps each file name to a ``(header, rows)`` pair. It does not
    touch the filesystem, which makes it useful for tests and custom writers.
    """

    numeric_seed = normalise_seed(seed)
    market_rows, participant_rows = _market_rows(numeric_seed)
    dataset: dict[str, tuple[tuple[str, ...], list[tuple[Any, ...]]]] = {
        "markets.csv": (MARKET_COLUMNS, market_rows),
        "participants.csv": (PARTICIPANT_COLUMNS, participant_rows),
        "edges.csv": (EDGE_COLUMNS, _edge_rows(numeric_seed, market_rows)),
        "prices.csv": (PRICE_COLUMNS, _price_rows(numeric_seed, market_rows)),
    }
    normalized = build_demo_normalized_tables(
        numeric_seed,
        start_date=PRICE_START_DATE,
        days=DEFAULT_PRICE_DAYS,
    )
    for table_name in NORMALIZED_TABLE_NAMES:
        table = normalized[table_name]
        dataset[f"{table_name}.csv"] = (
            tuple(table.columns),
            [tuple(row.get(column) for column in table.columns) for row in table],
        )
    return dataset


def _file_entry(path: str, digest: str, size: int, rows: int) -> dict[str, Any]:
    """Return a manifest entry describing one generated file."""

    return {
        "path": path,
        "name": path,
        "filename": path,
        "sha256": digest,
        "checksum": digest,
        "bytes": size,
        "size_bytes": size,
        "rows": rows,
        "row_count": rows,
    }


def _resolve_output(target: Path | str | None, overrides: Mapping[str, Any]) -> Path:
    """Pick the output directory from the supported keyword spellings."""

    candidates = [target]
    for key in ("out", "out_dir", "output_dir", "output"):
        candidates.append(overrides.get(key))
    for candidate in candidates:
        if candidate is not None:
            return Path(candidate)
    raise TypeError("an output directory is required")


class SyntheticGenerator:
    """Generate a deterministic synthetic dataset for a given seed."""

    name = GENERATOR_NAME
    version = __version__

    def __init__(self, seed: Any = DEFAULT_SEED) -> None:
        self.seed = normalise_seed(seed)

    def build(self) -> dict[str, tuple[tuple[str, ...], list[tuple[Any, ...]]]]:
        """Return the CSV contents this generator would write."""

        return build_dataset(self.seed)

    def generate(
        self,
        out_dir: Path | str | None = None,
        *,
        seed: Any | None = None,
        created_at: str | datetime | None = None,
        **kwargs: Any,
    ) -> dict[str, Any]:
        """Write the dataset below ``out_dir`` and return the manifest mapping.

        ``out``, ``out_dir`` and ``output_dir`` are accepted as keyword aliases
        for callers that use different naming conventions. Passing ``seed``
        overrides the generator's configured seed for this run.
        """

        if seed is not None:
            self.seed = normalise_seed(seed)
        destination = _resolve_output(out_dir, kwargs)
        destination.mkdir(parents=True, exist_ok=True)

        file_entries: list[dict[str, Any]] = []
        file_hashes: dict[str, str] = {}
        row_counts: dict[str, int] = {}
        dataset = self.build()

        for filename in SYNTHETIC_FILE_NAMES:
            header, rows = dataset[filename]
            text = _csv_text(header, rows)
            encoded = text.encode("utf-8")
            _atomic_write_text(destination / filename, text)
            digest = hashlib.sha256(encoded).hexdigest()
            file_entries.append(_file_entry(filename, digest, len(encoded), len(rows)))
            file_hashes[filename] = digest
            row_counts[filename] = len(rows)

        total_rows = sum(row_counts.values())
        table_schemas = {
            table_name: {
                "file": f"{table_name}.csv",
                "columns": list(SCHEMA_CONTRACTS[table_name].columns),
                "types": dict(SCHEMA_CONTRACTS[table_name].types),
                "units": dict(SCHEMA_CONTRACTS[table_name].units),
                "row_count": row_counts.get(f"{table_name}.csv", 0),
            }
            for table_name in NORMALIZED_TABLE_NAMES
        }
        metadata = {
            "generator": GENERATOR_NAME,
            "generator_version": __version__,
            "seed": self.seed,
            "synthetic": True,
            "row_counts": dict(row_counts),
            "tables": list(NORMALIZED_TABLE_NAMES),
            "schemas": table_schemas,
        }
        payload: dict[str, Any] = {
            "schema_version": MANIFEST_SCHEMA_VERSION,
            "generator": MANIFEST_GENERATOR,
            "generator_name": GENERATOR_NAME,
            "generator_version": __version__,
            "name": GENERATOR_NAME,
            "version": __version__,
            "profile": "synthetic",
            "data_source": "synthetic",
            "source": "synthetic",
            # Store the output-relative location so two runs with the same seed
            # produce identical manifests even when written to different
            # directories. ``write_manifest`` would otherwise record the
            # absolute destination path here.
            "data_dir": ".",
            "seed": self.seed,
            "synthetic": True,
            "file_count": len(file_entries),
            "files": file_entries,
            "file_hashes": dict(file_hashes),
            "checksums": dict(file_hashes),
            "hashes": dict(file_hashes),
            "row_counts": dict(row_counts),
            "rows": dict(row_counts),
            "row_count": total_rows,
            "total_rows": total_rows,
            "tables": list(NORMALIZED_TABLE_NAMES),
            "normalized_tables": list(NORMALIZED_TABLE_NAMES),
            "schemas": table_schemas,
            "metadata": metadata,
        }

        return write_manifest(destination, payload, created_at=created_at)

    # Friendly aliases so the generator can be used as a callable or writer.
    write = generate
    __call__ = generate


def generate_synthetic(
    out_dir: Path | str | None = None,
    seed: Any = DEFAULT_SEED,
    *,
    created_at: str | datetime | None = None,
    **kwargs: Any,
) -> dict[str, Any]:
    """Write deterministic synthetic CSVs and a manifest to ``out_dir``."""

    return SyntheticGenerator(seed=seed).generate(out_dir, created_at=created_at, **kwargs)


